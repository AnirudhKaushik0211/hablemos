'use strict';
// Curated-data statistics and integrity gate. Writes docs/EVAL.md deterministically (no clock, no randomness).
// The offline translator and its evaluation were retired (docs/SPEC.md, section 0). Online output comes from
// a third party and is not measured here.
//   node scripts/eval.cjs             check the curated data and the library-only fallback, write docs/EVAL.md
//   node scripts/eval.cjs --no-write  do not write docs/EVAL.md
const fs = require('fs');
const path = require('path');
const ROOT = path.resolve(__dirname, '..');
const api = {
  curated: require(path.join(ROOT, 'js', 'curated.js')),
  lexicon: require(path.join(ROOT, 'js', 'lexicon.js')),
  words: require(path.join(ROOT, 'data', 'words.js')),
  phrases: require(path.join(ROOT, 'data', 'phrases.js')),
  verbs: require(path.join(ROOT, 'data', 'verbs.js')),
  ff: require(path.join(ROOT, 'data', 'falsefriends.js')),
  idioms: require(path.join(ROOT, 'data', 'idioms.js')),
  pron: require(path.join(ROOT, 'data', 'pronunciation.js')),
  scenarios: require(path.join(ROOT, 'data', 'scenarios.js'))
};
const EVAL_MD = path.join(ROOT, 'docs', 'EVAL.md');
const MIN = { words: 1000, phrases: 300, verbs: 30, falseFriends: 20, idioms: 20 };

function counts() {
  const t = { A1: 0, A2: 0, B1: 0 }; const c = {};
  api.words.forEach((w) => { t[w.tier]++; c[w.cat] = (c[w.cat] || 0) + 1; });
  const pc = {};
  api.phrases.forEach((p) => { pc[p.cat] = (pc[p.cat] || 0) + 1; });
  return {
    words: api.words.length, tiers: t, wordCats: c, phrases: api.phrases.length, phraseCats: pc, verbs: api.verbs.length,
    falseFriends: api.ff.length, idioms: api.idioms.length, tips: api.pron.length, scenarios: api.scenarios.length,
    steps: api.scenarios.reduce((n, s) => n + s.steps.length, 0), cognates: api.words.filter((w) => w.cog).length
  };
}

// Fallback check: every library phrase finds itself, and what comes back is the authored string.
function fallbackCheck() {
  const allEs = new Set();
  api.words.forEach((w) => api.lexicon.variantEntries(w).forEach((v) => allEs.add(v.es)));
  api.phrases.forEach((p) => { allEs.add(p.es); Object.keys(p.var || {}).forEach((k) => allEs.add(p.var[k])); });
  let looked = 0, authored = 0;
  const bad = [];
  api.phrases.forEach((p) => {
    if (/\(/.test(p.en)) return;
    ['la', 'es'].forEach((v) => {
      const r = api.curated.lookup(p.en, v);
      looked++;
      if (r.phrase && allEs.has(r.phrase.es)) authored++; else bad.push(p.id + ' ' + v);
    });
  });
  const unmatched = api.curated.lookup('I am going to eat a quokka on Thursday', 'la');
  const refuses = !unmatched.phrase && unmatched.words.length === 0 && /does not generate Spanish/.test(unmatched.message);
  return { looked, authored, bad, refuses };
}

function md(cnt, fb, ok) {
  const L = [];
  L.push('# Hablemos: data statistics and fallback check');
  L.push('');
  L.push('Generated by `npm run eval` (`scripts/eval.cjs`). The file has no timestamps and is reproduced exactly by two runs.');
  L.push('');
  L.push('## Scope');
  L.push('');
  L.push('- The offline word-by-word translator and its dev and held-out evaluation were retired by an owner decision (`docs/SPEC.md`, section 0). There is nothing left to measure for it.');
  L.push('- Free-text translation is online only (MyMemory, a third-party service, after consent). Online output is not produced or checked by Hablemos and is **not covered by any accuracy gate or claim**.');
  L.push('- The curated content gate is unchanged: 0 errors in a reviewed sample of the authored data (words, phrases, idioms, false friends, scenario lines). That review is a separate step; this file records counts and an automatic fallback check.');
  L.push('');
  L.push('## Fallback check (no generated Spanish)');
  L.push('');
  L.push('| Check | Result |');
  L.push('|---|---|');
  L.push('| Library phrases looked up (variants la and es) | ' + fb.looked + ' |');
  L.push('| Returned Spanish that is an authored string from `data/` | ' + fb.authored + ' |');
  L.push('| Text with no exact match returns no Spanish and the "does not generate Spanish" message | ' + (fb.refuses ? 'yes' : 'NO') + ' |');
  L.push('| Verdict | **' + (ok ? 'PASS' : 'FAIL') + '** |');
  L.push('');
  L.push('## Data statistics');
  L.push('');
  L.push('| Item | Count |');
  L.push('|---|---|');
  L.push('| Words | ' + cnt.words + ' (A1 ' + cnt.tiers.A1 + ', A2 ' + cnt.tiers.A2 + ', B1 ' + cnt.tiers.B1 + ') |');
  L.push('| Cognates flagged | ' + cnt.cognates + ' |');
  L.push('| Phrases | ' + cnt.phrases + ' |');
  L.push('| Verbs | ' + cnt.verbs + ' |');
  L.push('| False friends | ' + cnt.falseFriends + ' |');
  L.push('| Idioms | ' + cnt.idioms + ' |');
  L.push('| Pronunciation tips | ' + cnt.tips + ' |');
  L.push('| Scenarios | ' + cnt.scenarios + ' (' + cnt.steps + ' steps) |');
  L.push('');
  L.push('Words per category:');
  L.push('');
  L.push('| Category | Words |');
  L.push('|---|---|');
  Object.keys(cnt.wordCats).sort().forEach((c) => L.push('| ' + c + ' | ' + cnt.wordCats[c] + ' |'));
  L.push('');
  L.push('Phrases per category:');
  L.push('');
  L.push('| Category | Phrases |');
  L.push('|---|---|');
  Object.keys(cnt.phraseCats).sort().forEach((c) => L.push('| ' + c + ' | ' + cnt.phraseCats[c] + ' |'));
  L.push('');
  return L.join('\n');
}

function main() {
  const cnt = counts();
  const fb = fallbackCheck();
  const sizeOk = cnt.words >= MIN.words && cnt.phrases >= MIN.phrases && cnt.verbs >= MIN.verbs && cnt.falseFriends >= MIN.falseFriends && cnt.idioms >= MIN.idioms;
  const ok = sizeOk && fb.refuses && fb.bad.length === 0;
  console.log('Words ' + cnt.words + ', phrases ' + cnt.phrases + ', verbs ' + cnt.verbs + ', false friends ' + cnt.falseFriends + ', idioms ' + cnt.idioms + '.');
  console.log('Fallback: ' + fb.authored + '/' + fb.looked + ' library lookups returned authored Spanish; unmatched text returns no Spanish: ' + fb.refuses + '.');
  if (fb.bad.length) console.log('Problems: ' + fb.bad.slice(0, 10).join(', '));
  if (process.argv.indexOf('--no-write') < 0) {
    fs.mkdirSync(path.dirname(EVAL_MD), { recursive: true });
    fs.writeFileSync(EVAL_MD, md(cnt, fb, ok), 'utf8');
    console.log('Wrote docs/EVAL.md');
  }
  if (!ok) { console.error('FAIL'); process.exit(1); }
  console.log('PASS');
}
main();
